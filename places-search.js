/* 이남노트: 장소 검색 규칙. 첫 화면(index.html)과 지도(map.html)가 같이 쓴다(2026-10-12).
   검색어를 바꾸는 말(SYN)이나 문 나누기(doorOf)는 여기서만 고친다. */
window.PlaceSearch = (() => {
  // 장소 → 지도의 큰 문. 문 없이 검색으로만 찾는 곳은 "etc"
  // 부동산(상가정보 대분류 '부동산', 공인중개사무소)은 검색 전용(etc)에서 문으로 꺼냈다(사용자 10-15 "편의점 옆에 부동산")
  const doorOf = p => p.cat === "etc" && p.kind === "부동산" ? "realty" : ["stay", "laundry", "coin", "golf", "school", "food", "etc"].includes(p.cat) ? p.cat : p.type === "편의점" ? "store" : "cafe";
  // 검색어 → 같이 찾을 말(업종 이름이 검색어와 다를 때만 적는다)
  const SYN = {
    "부동산": ["중개"], "중개": ["부동산"], "복덕방": ["부동산", "중개"],
    "병원": ["의원", "병원"], "의원": ["병원"], "약": ["약국"], "치과": ["치과"],
    "미용": ["미용", "헤어"], "헤어": ["미용"], "머리": ["미용", "이용", "헤어"],
    "숙소": ["숙박", "여관", "모텔", "호텔", "민박"], "모텔": ["숙박", "여관"], "잠": ["숙박", "여관", "모텔"],
    "빨래": ["빨래방", "세탁"], "세탁": ["빨래방"], "카페": ["커피", "까페"], "커피": ["카페", "까페"],
    // '마트'에서 편의점(122곳)은 뺐다 — 제 문이 있고, 마트 검색 202곳 중 절반을 넘었다(10-16)
    "마트": ["슈퍼", "식료품"], "슈퍼": ["마트", "식료품"], "밥": ["한식", "음식"], "고기": ["식육", "숯불"],
    // 음식(2026-10-13): 상가정보 세부 업종(menu_kind) 이름과 맞춘다. 메뉴를 넣은 가게는 메뉴 이름으로도 찾는다
    "짜장": ["중국집", "중국식"], "짜장면": ["중국집", "중국식"], "짬뽕": ["중국집", "중국식"], "중국집": ["중국식"],
    "국밥": ["국/탕", "국밥", "해장국", "순대"], "해장국": ["국/탕", "해장"], "찌개": ["찌개", "국/탕"], "탕": ["국/탕", "탕류"],
    "칼국수": ["국수/칼국수", "칼국수"], "국수": ["국수"], "냉면": ["냉면"], "회": ["횟집", "회/초밥"], "횟집": ["횟집"],
    "삼겹살": ["돼지고기", "삼겹", "오겹"], "돼지": ["돼지"], "소고기": ["소고기"], "곱창": ["곱창"], "족발": ["족발"], "보쌈": ["보쌈"],
    "치킨": ["치킨", "통닭"], "통닭": ["치킨"], "피자": ["피자"], "햄버거": ["버거"], "분식": ["김밥", "분식"], "김밥": ["김밥"],
    "백반": ["백반", "한정식"], "한정식": ["백반"], "술집": ["주점", "호프", "포차"], "호프": ["생맥주", "주점"],
    "애견": ["동물미용", "동물병원", "애완", "동물판매"], "강아지": ["동물미용", "동물병원", "애완", "동물판매"],
    "고양이": ["동물미용", "동물병원", "애완", "동물판매"], "분양": ["동물판매"], "이발": ["이발", "이용"], "네일": ["네일"],
    "학원": ["학원", "교습"], "세차": ["세차"], "정비": ["자동차 정비", "수리"], "철물": ["철물"], "골프": ["골프"],
  };
  // 업종 칸(이름 뺀 나머지)
  // also: 같은 가게라 합친 상가정보 줄의 업종(build_places.py drop_store_dups — 정육점으로 찾으면 고기백화점)
  const biz = p => (p.type + " " + p.kind + " " + (p.menu_kind || "") + " " + (p.subj || "") + " " + (p.also || []).join(" ") + " " +
    (p.menu || []).map(g => g.items.map(i => i[0]).join(" ")).join(" ")).toLowerCase();
  const hay = p => (p.name + " " + biz(p)).toLowerCase();
  const terms = q => q.toLowerCase().split(/\s+/).filter(Boolean);
  const words = t => [t, ...(SYN[t] || [])].map(w => w.toLowerCase());
  const matches = (p, q) => terms(q).every(t => words(t).some(w => hay(p).includes(w)));
  // 2026-10-16: 업종 말(어느 가게의 업종 칸에라도 나오는 말)로 찾으면 업종이 맞는 곳(main)과 이름에만 그 말이 든 곳(nameOnly)을 나눈다.
  // '마트'에 그린스마트시스템(가전)·한숲마트(세차장)·스마트해법수학이 섞였다(사용자). 이름 규칙으로 하나씩 막지 않고, 빼지도 않고 뒤로 돌린다.
  // 가게 이름으로 찾는 말('하나로마트')은 업종 칸에 없으므로 전부 main이다.
  const split = (list, q) => {
    const hit = list.filter(p => matches(p, q));
    const cat = terms(q).filter(t => words(t).some(w => list.some(p => biz(p).includes(w))));
    if (!cat.length) return { main: hit, nameOnly: [] };
    // 이름을 믿는 곳: 식당·카페(이름이 곧 파는 것 — 이동불고기가 '한식'이라 '고기'에서 밀렸다)와
    // 업종이 '기타'·'일반조리판매'처럼 뭉뚱그려진 곳(가마치통닭이 업종 '기타'라 '치킨'에서 밀렸다)
    const vague = p => /^(기타( 휴게음식점)?|그 외 기타 .+|일반조리판매)?$/.test((p.menu_kind || p.type || "").trim());
    const ok = p => ["food", "cafe"].includes(doorOf(p)) || vague(p) || cat.every(t => words(t).some(w => biz(p).includes(w)));
    const main = hit.filter(ok), nameOnly = hit.filter(p => !ok(p));
    return main.length ? { main, nameOnly } : { main: nameOnly, nameOnly: [] };
  };
  return { doorOf, SYN, matches, split };
})();
